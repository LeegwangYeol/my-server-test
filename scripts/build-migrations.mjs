#!/usr/bin/env node
/**
 * Reads every supabase/migrations/*.sql file and emits a TS module that
 * inlines them as string constants. The migration-runner endpoint
 * imports this module instead of reading the filesystem at runtime
 * (Vercel function bundles don't include adjacent files by default).
 *
 * Re-run before each esbuild. Wired into `npm run bundle:api`.
 */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";

const root = process.cwd();
const dir = join(root, "supabase/migrations");
const out = join(root, "src/generated-migrations.ts");

const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort(); // lexicographic = timestamp order

const entries = files.map((f) => ({
  name: f,
  content: readFileSync(join(dir, f), "utf8"),
}));

const ts = `// AUTO-GENERATED by scripts/build-migrations.mjs. Do not edit.
// Re-run \`node scripts/build-migrations.mjs\` after adding a new .sql file.

export interface MigrationFile {
  name: string;
  content: string;
}

export const MIGRATIONS: MigrationFile[] = ${JSON.stringify(entries, null, 2)};
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, ts);
console.log(`generated ${entries.length} migrations → ${out}`);
